def render_html(payload: Dict[str, Any]) -> str:
    """Render the analysis payload as a standalone HTML report."""
    prediction = payload.get("prediction") or {}
    patient = payload.get("patient") or {}
    explainability = payload.get("explainability") or {}

    meta_rows = "\n".join(
        f'<div class="kv"><span>{html.escape(str(key))}</span><span>{html.escape(str(value))}</span></div>'
        for key, value in _report_header_rows(payload)
    )

    severity = str(prediction.get("severity", "normal"))
    severity_class = "bad" if severity in {"severe", "critical"} else ("good" if severity == "normal" else "")

    probabilities = prediction.get("class_probabilities") or {}
    probability_block = ""
    if probabilities:
        rows = "\n".join(
            f'<tr><td>{html.escape(str(label))}</td><td class="num">{value:.1%}</td></tr>'
            for label, value in sorted(probabilities.items(), key=lambda item: item[1], reverse=True)
        )
        probability_block = (
            "<h2>Class probability distribution</h2><div class='card'><table>"
            f"<thead><tr><th>Condition</th><th style='text-align:right'>Probability</th></tr></thead><tbody>{rows}</tbody></table></div>"
        )

    findings = payload.get("findings") or []
    finding_rows = "\n".join(
        "<tr>"
        f"<td>{html.escape(str(f.get('name', '-')))}</td>"
        f"<td>{html.escape(str(f.get('value', '-')))} {html.escape(str(f.get('unit') or ''))}</td>"
        f"<td class='note'>{html.escape(str(f.get('reference_range', '-')))}</td>"
        f"<td><span class='pill'>{html.escape(str(f.get('status', '-')).title())}</span></td>"
        "</tr>"
        for f in findings
    )

    top_features = explainability.get("top_features") or []
    feature_block = ""
    if top_features:
        rows = "\n".join(
            f"<tr><td>{html.escape(str(f.get('name', '-')))}</td>"
            f"<td class='num'>{float(f.get('contribution', 0)):.3f}</td>"
            f"<td class='note'>{html.escape(str(f.get('direction', '-')).replace('_', ' ').title())}</td></tr>"
            for f in top_features
        )
        feature_block = (
            "<h3 style='font-size:13px;margin:16px 0 6px'>Leading feature contributions</h3>"
            f"<table><thead><tr><th>Feature</th><th style='text-align:right'>Contribution</th><th>Direction</th></tr></thead><tbody>{rows}</tbody></table>"
        )

    visuals = ""
    for key, caption in (
        ("saliency_png_base64", "Signal attribution"),
        ("overlay_png_base64", "Grad-CAM localisation"),
        ("waveform_png_base64", "Conditioned recording"),
    ):
        data = explainability.get(key)
        if data:
            visuals += (
                f"<h3 style='font-size:13px;margin:16px 0 4px'>{caption}</h3>"
                f"<img class='visual' alt='{caption}' src='data:image/png;base64,{data}'>"
            )
    visual_block = visuals

    recommendation_items = "\n".join(
        f"<li>{html.escape(str(item))}</li>" for item in (payload.get("recommendations") or [])
    )

    confidence = float(prediction.get("confidence", 0) or 0)

    return _HTML_TEMPLATE.format(
        app_title=html.escape(settings.app_title),
        analysis_id=html.escape(str(payload.get("analysis_id", "-"))),
        created_at=html.escape(str(payload.get("created_at", "-"))),
        meta_rows=meta_rows,
        label=html.escape(str(prediction.get("label", "-"))),
        description=html.escape(str(prediction.get("description", ""))),
        severity=html.escape(severity.title()),
        severity_class=severity_class,
        confidence=f"{confidence:.1%}",
        confidence_pct=f"{max(0.0, min(1.0, confidence)) * 100:.1f}%",
        probability_block=probability_block,
        finding_rows=finding_rows,
        explain_summary=html.escape(str(explainability.get("summary", ""))),
        attribution_method=html.escape(str(explainability.get("attribution_method", "-"))),
        feature_block=feature_block,
        visual_block=visual_block,
        recommendation_items=recommendation_items,
        disclaimer=html.escape(DISCLAIMER),
    )


