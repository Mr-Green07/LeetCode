def generate_report(analysis_id: str, fmt: str = "pdf") -> Dict[str, Any]:
    """Render and persist a report for ``analysis_id``."""
    fmt = fmt.lower()
    if fmt not in {"pdf", "html", "json"}:
        raise ValidationError("Unsupported report format. Use pdf, html or json.")

    payload = _load_payload(analysis_id)
    report_id = new_id(prefix="rep-")
    target_dir = Path(settings.report_dir)
    target_dir.mkdir(parents=True, exist_ok=True)

    if fmt == "pdf":
        data = render_pdf(payload)
        path = target_dir / f"{report_id}.pdf"
        path.write_bytes(data)
        media_type = "application/pdf"
    elif fmt == "html":
        data = render_html(payload).encode("utf-8")
        path = target_dir / f"{report_id}.html"
        path.write_bytes(data)
        media_type = "text/html"
    else:
        import json

        data = json.dumps(payload, indent=2, default=str).encode("utf-8")
        path = target_dir / f"{report_id}.json"
        path.write_bytes(data)
        media_type = "application/json"

    record_report(
        report_id=report_id,
        analysis_id=analysis_id,
        fmt=fmt,
        path=str(path),
        size_bytes=len(data),
    )
    logger.info("Generated %s report %s for %s", fmt, report_id, analysis_id)

    return {
        "report_id": report_id,
        "analysis_id": analysis_id,
        "format": fmt,
        "path": str(path),
        "media_type": media_type,
        "size_bytes": len(data),
        "created_at": datetime.now(timezone.utc).isoformat(),
    }


def reports_for_analysis(analysis_id: str) -> List[Dict[str, Any]]:
    """List reports previously generated for an analysis."""
    return list_reports(analysis_id)
