"""Automated diagnostic report rendering.

Two formats are produced from the same analysis payload:

* **PDF** - a formal, printable report for the clinical record;
* **HTML** - the same content in a browser-friendly layout.

Both embed the explainability visuals so a clinician can see *why* the model
reached its conclusion.
"""

from __future__ import annotations

import base64
import html
import io
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from app.config import settings
from app.core.audit import get_analysis, list_reports, record_report
from app.core.errors import NotFoundError, ValidationError
from app.core.logging import get_logger
from app.core.storage import load_analysis_payload, new_id

logger = get_logger(__name__)

DISCLAIMER = (
    "This report was generated by an AI decision-support tool. It is not a medical diagnosis and "
    "must be interpreted by a qualified healthcare professional alongside the complete patient record, "
    "physical examination and confirmatory investigations."
)


# --------------------------------------------------------------------------- #
# Shared helpers
# --------------------------------------------------------------------------- #
def _decode_png(data: Optional[str]) -> Optional[bytes]:
    if not data:
        return None
    try:
        return base64.b64decode(data)
    except Exception:  # pragma: no cover - defensive
        return None


def _format_probability(value: float) -> str:
    try:
        return f"{float(value):.1%}"
    except (TypeError, ValueError):
        return "-"


def _load_payload(analysis_id: str) -> Dict[str, Any]:
    """Load an analysis payload from disk or the audit database."""
    payload = load_analysis_payload(analysis_id)
    if payload:
        return payload
    row = get_analysis(analysis_id)
    if row and row.get("payload"):
        return {"analysis_id": analysis_id, **row["payload"]}
    raise NotFoundError(f"No analysis found with id {analysis_id}")


def _report_header_rows(payload: Dict[str, Any]) -> List[Tuple[str, str]]:
    patient = payload.get("patient") or {}
    prediction = payload.get("prediction") or {}
    created = payload.get("created_at") or ""
    return [
        ("Analysis ID", str(payload.get("analysis_id", "-"))),
        ("Modality", str(payload.get("modality", "-")).upper()),
        ("Patient reference", str(patient.get("patient_id", "-"))),
        ("Age / Sex", f"{patient.get('age', '-')} / {patient.get('sex', 'unknown')}"),
        ("Referring clinician", str(patient.get("referring_clinician") or "-")),
        ("Generated at", str(created)),
        ("Model version", str(payload.get("model_version", "-"))),
        ("Model source", str(payload.get("model_source", "-"))),
    ]


# --------------------------------------------------------------------------- #
# PDF rendering
# --------------------------------------------------------------------------- #
def render_pdf(payload: Dict[str, Any]) -> bytes:
    """Render the analysis payload as a PDF report."""
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_LEFT
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import (
        Image,
        KeepTogether,
        Paragraph,
        SimpleDocTemplate,
        Spacer,
        Table,
        TableStyle,
    )

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=16 * mm,
        bottomMargin=16 * mm,
        title=f"Diagnostic report {payload.get('analysis_id', '')}",
        author=str(settings.app_title),
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "MedTitle", parent=styles["Title"], fontSize=17, leading=21, alignment=TA_LEFT, spaceAfter=2
    )
    subtitle_style = ParagraphStyle(
        "MedSub", parent=styles["Normal"], fontSize=9.5, textColor=colors.HexColor("#5b6474"), spaceAfter=10
    )
    section_style = ParagraphStyle(
        "MedSection", parent=styles["Heading2"], fontSize=12, leading=15, spaceBefore=12, spaceAfter=5,
        textColor=colors.HexColor("#1f2a3a"),
    )
    body_style = ParagraphStyle("MedBody", parent=styles["Normal"], fontSize=9, leading=13)
    small_style = ParagraphStyle("MedSmall", parent=styles["Normal"], fontSize=7.6, leading=10, textColor=colors.HexColor("#5b6474"))
    diagnosis_style = ParagraphStyle(
        "MedDiag", parent=styles["Normal"], fontSize=13, leading=17, textColor=colors.HexColor("#b3261e")
    )

    story: List[Any] = []

    story.append(Paragraph(f"{settings.app_title} - Diagnostic Report", title_style))
    story.append(
        Paragraph(
            "Automated clinical decision-support report generated from ECG, EEG or chest radiograph input.",
            subtitle_style,
        )
    )

    # ---- header table
    header_data = [[key, value] for key, value in _report_header_rows(payload)]
    header_table = Table(header_data, colWidths=[52 * mm, 112 * mm])
    header_table.setStyle(
        TableStyle(
            [
                ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 8.5),
                ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#3b4a5d")),
                ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f2f5f9")),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#d8dee8")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ]
        )
    )
    story.append(header_table)

    # ---- primary diagnosis
    prediction = payload.get("prediction") or {}
    story.append(Paragraph("Primary Diagnosis", section_style))
    diagnosis_box = Table(
        [
            ["Condition", str(prediction.get("label", "-"))],
            ["Confidence", _format_probability(prediction.get("confidence", 0))],
            ["Severity", str(prediction.get("severity", "-")).title()],
            ["Interpretation", str(prediction.get("description", "-"))],
        ],
        colWidths=[38 * mm, 126 * mm],
    )
    diagnosis_box.setStyle(
        TableStyle(
            [
                ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("BACKGROUND", (0, 0), (0, 0), colors.HexColor("#fdecea")),
                ("TEXTCOLOR", (1, 0), (1, 0), colors.HexColor("#b3261e")),
                ("FONTNAME", (1, 0), (1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (1, 0), (1, 0), 13),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#e3e7ee")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]
        )
    )
    story.append(diagnosis_box)

    # ---- differential / class probabilities
    probabilities = prediction.get("class_probabilities") or {}
    if probabilities:
        story.append(Paragraph("Class Probability Distribution", section_style))
        rows = [["Condition", "Probability"]]
        rows += [[str(label), _format_probability(value)] for label, value in sorted(probabilities.items(), key=lambda item: item[1], reverse=True)]
        prob_table = Table(rows, colWidths=[110 * mm, 54 * mm])
        prob_table.setStyle(
            TableStyle(
                [
                    ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                    ("FONTSIZE", (0, 0), (-1, -1), 8.5),
                    ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#d8dee8")),
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eef2f8")),
                    ("ALIGN", (1, 1), (1, -1), "RIGHT"),
                    ("TOPPADDING", (0, 0), (-1, -1), 3),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                ]
            )
        )
        story.append(prob_table)

    # ---- clinical findings
    findings = payload.get("findings") or []
    if findings:
        story.append(Paragraph("Clinical Findings", section_style))
        rows = [["Finding", "Value", "Reference", "Status"]]
        for finding in findings:
            rows.append(
                [
                    str(finding.get("name", "-")),
                    f"{finding.get('value', '-')} {finding.get('unit') or ''}".strip(),
                    str(finding.get("reference_range", "-")),
                    str(finding.get("status", "-")).title(),
                ]
            )
        findings_table = Table(rows, colWidths=[56 * mm, 32 * mm, 52 * mm, 24 * mm], repeatRows=1)
        findings_table.setStyle(
            TableStyle(
                [
                    ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                    ("FONTSIZE", (0, 0), (-1, -1), 7.8),
                    ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#d8dee8")),
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eef2f8")),
                    ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                    ("TOPPADDING", (0, 0), (-1, -1), 2.5),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
                ]
            )
        )
        story.append(findings_table)

    # ---- explainability
    explainability = payload.get("explainability") or {}
    story.append(Paragraph("Explainable AI Analysis", section_style))
    if explainability.get("summary"):
        story.append(Paragraph(html.escape(str(explainability["summary"])), body_style))
        story.append(Spacer(1, 4))
    if explainability.get("attribution_method"):
        story.append(Paragraph(f"Attribution method: {html.escape(str(explainability['attribution_method']))}", small_style))
        story.append(Spacer(1, 4))

    for key, caption in (
        ("saliency_png_base64", "Signal attribution map"),
        ("overlay_png_base64", "Grad-CAM localisation"),
        ("waveform_png_base64", "Conditioned recording"),
    ):
        png = _decode_png(explainability.get(key))
        if png:
            try:
                img = Image(io.BytesIO(png), width=165 * mm, height=56 * mm)
                img.hAlign = "LEFT"
                story.append(KeepTogether([Paragraph(caption, body_style), img, Spacer(1, 6)]))
            except Exception as exc:  # pragma: no cover - defensive
                logger.error("Could not embed %s in PDF: %s", key, exc)

    top_features = explainability.get("top_features") or []
    if top_features:
        story.append(Paragraph("Leading Feature Contributions", section_style))
        rows = [["Feature", "Contribution", "Direction"]]
        for feature in top_features:
            rows.append(
                [
                    str(feature.get("name", "-")),
                    f"{float(feature.get('contribution', 0)):.3f}",
                    str(feature.get("direction", "-")).replace("_", " ").title(),
                ]
            )
        feature_table = Table(rows, colWidths=[92 * mm, 40 * mm, 32 * mm])
        feature_table.setStyle(
            TableStyle(
                [
                    ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                    ("FONTSIZE", (0, 0), (-1, -1), 8),
                    ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#d8dee8")),
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eef2f8")),
                    ("TOPPADDING", (0, 0), (-1, -1), 2.5),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
                ]
            )
        )
        story.append(feature_table)

    # ---- recommendations
    recommendations = payload.get("recommendations") or []
    if recommendations:
        story.append(Paragraph("Clinical Recommendations", section_style))
        for index, advice in enumerate(recommendations, start=1):
            story.append(Paragraph(f"{index}. {html.escape(str(advice))}", body_style))
            story.append(Spacer(1, 2))

    # ---- quality
    quality = payload.get("quality") or {}
    story.append(Paragraph("Input Quality", section_style))
    story.append(
        Paragraph(
            f"Signal quality index: <b>{quality.get('signal_quality_index', '-')}</b> &nbsp;|&nbsp; "
            f"Usable: <b>{'yes' if quality.get('usable') else 'no'}</b> &nbsp;|&nbsp; "
            f"SNR: <b>{quality.get('snr_db', '-')} dB</b>",
            body_style,
        )
    )

    # ---- disclaimer
    story.append(Spacer(1, 8))
    disclaimer_table = Table([[Paragraph(html.escape(DISCLAIMER), small_style)]], colWidths=[164 * mm])
    disclaimer_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#fff8e6")),
                ("BOX", (0, 0), (-1, -1), 0.6, colors.HexColor("#e8c765")),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ]
        )
    )
    story.append(disclaimer_table)

    doc.build(story)
    return buffer.getvalue()


